import hashlib, json, sys

OUT = []


def _id(q):
    return 'q_' + hashlib.sha1(q.encode('utf-8')).hexdigest()[:8]


def C(topic, src, q, opts, expl, level=1):
    OUT.append(dict(id=_id(q), format='choice', topic=topic, level=level, question=q,
                    options=opts, correct=0, explanation=f'{opts[0]} ({expl})', source=src))


def Y(topic, src, q, ok, expl, level=1):
    OUT.append(dict(id=_id(q), format='yesno', topic=topic, level=level, question=q,
                    correct=ok, explanation=f"{'Да' if ok else 'Нет'} ({expl})", source=src))


def I(topic, src, q, ans, acc, expl, level=2):
    OUT.append(dict(id=_id(q), format='input', topic=topic, level=level, question=q, answer=ans,
                    accepted=[a.lower() for a in acc], explanation=f'{ans} ({expl})', source=src))


